        // connect
        let (ack, rx) = tokio::sync::oneshot::channel();
        tx.send(Cmd::SetTunnel(vec!["10.64.0.1".parse().unwrap()], ack))
            .await
            .unwrap();
        rx.await.unwrap().unwrap();
        // WAN file changes while connected — mirror must NOT clobber tunnel resolvers
        std::fs::write(&paths.wan, "nameserver 192.0.2.53\n").unwrap();
