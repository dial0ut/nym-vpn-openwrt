        std::fs::write(&paths.wan, "nameserver 198.51.100.53\n").unwrap();
        tokio::time::sleep(std::time::Duration::from_millis(12_000)).await;
        assert!(std::fs::read_to_string(&paths.managed).unwrap().contains("198.51.100.53"));
